package grpcauth

import (
	"context"
	"strings"

	"github.com/ds454/auth/src/config"
	"github.com/ds454/auth/src/log"
	corev3 "github.com/envoyproxy/go-control-plane/envoy/config/core/v3"
	authv3 "github.com/envoyproxy/go-control-plane/envoy/service/auth/v3"
	typev3 "github.com/envoyproxy/go-control-plane/envoy/type/v3"
	rpcstatus "google.golang.org/genproto/googleapis/rpc/status"
	"google.golang.org/grpc/codes"
)

var _sessionKeyLength int = (int)(config.GetConfig().SessionKeyLen)
var _sessionTokenKey string = config.GetConfig().SessionTokenKey

func (s *AuthServer) Check(ctx context.Context, req *authv3.CheckRequest) (*authv3.CheckResponse, error) {
	log.Debug("Received authentication request")

	// Get the session token from the request
	headers := req.GetAttributes().GetRequest().GetHttp().GetHeaders()
	sessionToken := headers[strings.ToLower(_sessionTokenKey)]

	if strings.TrimSpace(sessionToken) == "" {
		return deny(codes.Unauthenticated, typev3.StatusCode_Unauthorized, "missing session token"), nil
	}

	// Quick bounds checking
	if len(sessionToken) != _sessionKeyLength {
		log.Warn("Received session key that is the wrong length, someone may be trying to break in.")
		return deny(codes.Unauthenticated, typev3.StatusCode_Unauthorized, "invalid session token"), nil
	}

	// Check if the session is valid by trying to get the uuid matching the
	dataFromRedis, err := s.Redis.HMGet(ctx, sessionTokenPrefix+sessionToken, "uuid", "stmid").Result()
	if err != nil {
		log.Error("Problem checking if session is valid:")
		log.Error("%v", err)
		return deny(codes.Unavailable, typev3.StatusCode_ServiceUnavailable, ""), nil
	}

	var uuid, steamId string
	if dataFromRedis[0] != nil {
		uuid = dataFromRedis[0].(string)
	}
	if dataFromRedis[1] != nil {
		steamId = dataFromRedis[1].(string)
	}

	// Confirm the uuid exists
	if strings.TrimSpace(uuid) == "" {
		log.Debug("Session token %s exists, but does not have a valid uuid", sessionToken)
		return deny(codes.Unauthenticated, typev3.StatusCode_Unauthorized, "invalid session"), nil
	}

	// Confirm the steamId exists
	if strings.TrimSpace(steamId) == "" {
		log.Debug("Session token %s exists, but does not have a valid steam id", sessionToken)
		return deny(codes.Unauthenticated, typev3.StatusCode_Unauthorized, "invalid session"), nil
	}

	return allow(uuid, steamId), nil
}

// Generated by Claude
func allow(uuid string, steamId string) *authv3.CheckResponse {
	return &authv3.CheckResponse{
		Status: &rpcstatus.Status{Code: int32(codes.OK)},
		HttpResponse: &authv3.CheckResponse_OkResponse{
			OkResponse: &authv3.OkHttpResponse{
				// Headers to add to downstream requests
				Headers: []*corev3.HeaderValueOption{
					{
						Header: &corev3.HeaderValue{
							Key:   config.GetConfig().UuidMetadataKey,
							Value: uuid,
						},
						AppendAction: corev3.HeaderValueOption_OVERWRITE_IF_EXISTS_OR_ADD,
					},
					{
						Header: &corev3.HeaderValue{
							Key:   config.GetConfig().SteamIdMetadataKey,
							Value: steamId,
						},
						AppendAction: corev3.HeaderValueOption_OVERWRITE_IF_EXISTS_OR_ADD,
					},
				},
				// Keep the raw session token away from backends
				HeadersToRemove: []string{_sessionTokenKey},
			},
		},
	}
}

// Generated by Claude
// Envoy turns the HTTP status into the client's gRPC status
// (401 -> UNAUTHENTICATED, 503 -> UNAVAILABLE) and the body into its message.
func deny(code codes.Code, httpCode typev3.StatusCode, msg string) *authv3.CheckResponse {
	return &authv3.CheckResponse{
		Status: &rpcstatus.Status{Code: int32(code), Message: msg},
		HttpResponse: &authv3.CheckResponse_DeniedResponse{
			DeniedResponse: &authv3.DeniedHttpResponse{
				Status: &typev3.HttpStatus{Code: httpCode},
				Body:   msg,
			},
		},
	}
}
